// build-hue.mjs - the color wheel's rules, generated from the warm look itself (v7.64).
//
//   node tools/build-hue.mjs          rewrite the generated block at the end of each sheet
//   node tools/build-hue.mjs --check  exit 1 if a sheet's block is not what its own rules make
//
// Eric, 2026-10-17: "Keep the whole color scheme and gradient, but allow it to be adjusted via a color wheel in
// settings." Every colour in warm.css and landing-warm.css is turned round the wheel by the hue he picks, so the
// look stays the same look in another colour. Each rule that carries a colour is repeated at the end of its own
// sheet with that colour as oklch(from <colour> l c calc(h + var(--pa-hue)) / alpha), behind:
//   - @supports for relative colour, so a browser without it keeps the warm look untouched;
//   - the warm look's own guards plus [data-hue], set before paint only when a hue is chosen, so the default is byte for byte the
//     warm look, and :where keeps every rule at the specificity it had (it wins on order, as the last word in its
//     own sheet, and loses to whatever already beat the original).
// Rules for High contrast and for Blue and purple, keyframes, and the Settings swatches are left as they are.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SHEETS = ['public/css/warm.css', 'public/css/landing-warm.css'];
const START = '/* ==== THE COLOR WHEEL (generated by tools/build-hue.mjs from the rules above; do not edit by hand) ==== */';
const END = '/* ==== END OF THE COLOR WHEEL ==== */';
const COLOR = /#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3,4}\b|rgba?\([^()]*\)/g;
const turn = (c) => `oklch(from ${c} l c calc(h + var(--pa-hue)) / alpha)`;
// The warm look's root: not High contrast, not Blue and purple.
export const WARM_ROOT = ':root:not([data-scheme="contrast"]):not([data-look="cool"])';
// What a colour means stays put: success is green, an error red, a warning gold, whatever the wheel says.
const MEANING = new Set(['--green', '--danger', '--gold']);

/** The sheet without its generated block. */
export function source(css) {
  const at = css.indexOf(START);
  return (at < 0 ? css : css.slice(0, at)).replace(/\s+$/, '\n');
}

/** Top-level blocks of a stylesheet: [prelude, body] pairs, comments gone. */
function blocks(css) {
  const out = [];
  const s = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let i = 0;
  while (i < s.length) {
    const open = s.indexOf('{', i);
    if (open < 0) break;
    const prelude = s.slice(i, open).trim();
    let depth = 1; let j = open + 1;
    for (; j < s.length && depth; j++) { if (s[j] === '{') depth++; else if (s[j] === '}') depth--; }
    out.push([prelude, s.slice(open + 1, j - 1)]);
    i = j;
  }
  return out;
}

// Selectors that are not the warm look's own: High contrast's, Blue and purple's, the Settings swatches.
const foreign = (sel) => /\.sc-/.test(sel)
  || (/\[data-scheme="contrast"\]/.test(sel) && !/:not\(\[data-scheme="contrast"\]\)/.test(sel))
  || (/\[data-look="cool"\]/.test(sel) && !/:not\(\[data-look="cool"\]\)/.test(sel));

/** Where a selector's first compound ends: the first space or combinator outside brackets. */
function firstCompound(s) {
  let d = 0;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === '(' || c === '[') d++; else if (c === ')' || c === ']') d--;
    else if (!d && /[\s>+~]/.test(c)) return i;
  }
  return s.length;
}

/**
 * One selector, scoped to a chosen hue without moving its specificity. A rule
 * on the root keeps every guard it had (not High contrast, not Blue and purple)
 * and gains :where([data-hue]) after them; any other rule is put under the
 * same guards, inside :where so they add nothing to its weight.
 */
function scope(sel) {
  const s = sel.trim();
  if (/^(:root|html\b|:where\(:root)/.test(s)) { const k = firstCompound(s); return `${s.slice(0, k)}:where([data-hue])${s.slice(k)}`; }
  return `:where(${WARM_ROOT}[data-hue]) ${s}`;
}

// Properties that put colour on the page, with every longhand of a shorthand that does (a repeated `background`
// resets background-clip, so a gradient written into text would fill its box if the clip were left behind).
const PAINT = /^(-webkit-)?(background|border|outline|text-decoration|column-rule)(-[a-z-]+)?$|^(color|box-shadow|text-shadow|fill|stroke|caret-color|accent-color|-webkit-text-fill-color|-webkit-text-stroke(-color)?|scrollbar-color|filter|stop-color)$/;
const paints = (prop, value) => {
  if (prop.startsWith('--')) { COLOR.lastIndex = 0; return COLOR.test(value) || /var\(/.test(value); }
  return PAINT.test(prop);
};

const splitTop = (str, ch) => { const out = []; let d = 0; let cur = ''; for (const c of str) { if (c === '(') d++; if (c === ')') d--; if (c === ch && !d) { out.push(cur); cur = ''; } else cur += c; } if (cur.trim()) out.push(cur); return out; };

function rules(css, indent = '  ') {
  const out = [];
  for (const [prelude, body] of blocks(css)) {
    if (/^@keyframes|^@font-face/.test(prelude)) continue;
    if (/^@media/.test(prelude)) {
      const inner = rules(body, `${indent}  `);
      if (inner.length) out.push(`${indent}${prelude} {\n${inner.join('\n')}\n${indent}}`);
      continue;
    }
    if (prelude.startsWith('@')) continue;
    const sels = splitTop(prelude, ',').map((x) => x.trim()).filter((x) => x && !foreign(x));
    if (!sels.length) continue;
    // Every paint declaration comes along, coloured or not, so a later rule that paints with var() still beats
    // the earlier rule it beat before; only the colours written out are turned.
    const decls = splitTop(body, ';').map((d) => d.trim()).filter((d) => d.includes(':'))
      .filter((d) => { const prop = d.slice(0, d.indexOf(':')).trim().toLowerCase(); return !MEANING.has(prop) && paints(prop, d.slice(d.indexOf(':') + 1)); })
      .map((d) => { const k = d.indexOf(':'); return `${d.slice(0, k).trim()}: ${d.slice(k + 1).trim().replace(COLOR, turn)};`; });
    if (!decls.length) continue;
    out.push(`${indent}${sels.map(scope).join(',\n' + indent)} {\n${decls.map((d) => `${indent}  ${d}`).join('\n')}\n${indent}}`);
  }
  return out;
}

/** The whole sheet, its generated block made from its own rules. */
export function build(css) {
  const src = source(css);
  const made = rules(src, '  ');
  return `${src}\n${START}\n@supports (color: oklch(from red l c calc(h + 10) / alpha)) {\n${made.join('\n')}\n}\n${END}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const p of SHEETS) {
    const css = readFileSync(join(ROOT, p), 'utf8');
    const next = build(css);
    if (next === css) { console.log(`ok     ${p}`); continue; }
    if (check) { stale += 1; console.log(`STALE  ${p}`); } else { writeFileSync(join(ROOT, p), next); console.log(`built  ${p}`); }
  }
  if (stale) process.exit(1);
}
