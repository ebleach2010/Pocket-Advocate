// sync-rules.mjs - writes worker/rules-text.js from firestore.rules and storage.rules.
//
// The Worker publishes the security rules itself (worker/rules-release.js),
// because Eric cannot run a deploy command from his phone. It can only publish
// what it was built with, so the two files are copied into a module here, byte
// for byte; tools/suites/rulesync.mjs fails the battery whenever the module and
// the files disagree. Run after any change to either rules file:
//   node tools/rules/sync-rules.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const fsRules = readFileSync(join(ROOT, 'firestore.rules'), 'utf8');
const stRules = readFileSync(join(ROOT, 'storage.rules'), 'utf8');
// Anything past ASCII is written as a \u escape: the strings are the same
// once parsed, and the module itself stays plain ASCII.
const ascii = (s) => JSON.stringify(s).replace(/[\u0080-\uffff]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
writeFileSync(join(ROOT, 'worker/rules-text.js'), `// GENERATED by tools/rules/sync-rules.mjs from firestore.rules and storage.rules.
// Do not edit by hand: change the .rules files and run the script. The battery
// (rulesync.mjs) fails while this and the files disagree.
export const FIRESTORE_RULES = ${ascii(fsRules)};
export const STORAGE_RULES = ${ascii(stRules)};
`);
console.log('worker/rules-text.js written');
